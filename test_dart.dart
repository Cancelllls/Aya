void main() {
  String text = "بِسْمِ اللَّهِ الرَّحْمَٰنِ الرَّحِيمِ الم";
  final basmalahs = [
    "بِسْمِ ٱللَّهِ ٱلرَّحْمَٰنِ ٱلرَّحِيمِ",
    "بِسْمِ ٱللَّهِ ٱلرَّحْمَنِ ٱلرَّحِيمِ",
    "بِسْمِ ٱللهِ ٱلرَّحْمَنِ ٱلرَّحِيمِ",
    "بِسْمِ اللَّهِ الرَّحْمَٰنِ الرَّحِيمِ",
    "بِسْمِ اللهِ الرَّحْمَنِ الرَّحِيمِ",
    "بِسْمِ اللهِ الرَّحْمٰنِ الرَّحِيْمِ",
    "بِسْمِ اللَّهِ الرَّحْمَنِ الرَّحِيمِ",
    "بِسْمِ اللهِ الرَّحْمَٰنِ الرَّحِيمِ",
  ];
  for (final basmalah in basmalahs) {
    if (text.startsWith(basmalah)) {
      print("Match: " + basmalah);
      print("Cleaned: " + text.substring(basmalah.length).trim());
      return;
    }
  }
  print("No match!");
}
